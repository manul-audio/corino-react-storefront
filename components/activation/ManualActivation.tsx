'use client'

import { ActivationMethod, useInventory, type License } from '@moonbase.sh/react'
import dynamic from 'next/dynamic'
import { useState } from 'react'
import { ActivationProductCard } from '@/components/activation/ProductCard'

// The file reader is browser-only and only needed on this page.
const DeviceTokenInput = dynamic(
  () => import('@/components/activation/DeviceTokenInput').then((m) => m.DeviceTokenInput),
  { ssr: false },
)

export function ManualActivation() {
  const { activateProduct } = useInventory()
  const [step, setStep] = useState<'input' | 'uploading' | 'done'>('input')
  const [error, setError] = useState<Error | null>(null)
  const [result, setResult] = useState<{ license: License; url: string } | null>(null)

  async function handleToken(token: string) {
    setError(null)
    setStep('uploading')
    try {
      setResult(await activateProduct(token, ActivationMethod.Offline))
      setStep('done')
    } catch (err) {
      setError(err as Error)
      setStep('input')
    }
  }

  function reset() {
    setError(null)
    setResult(null)
    setStep('input')
  }

  return (
    <div className="manual-activation">
      <p className="hint">
        Upload your machine file here to get a license file for activating offline devices.
        The machine file is generated by the plugin running on the device.
      </p>
      {step === 'input' ? <DeviceTokenInput error={error} onToken={handleToken} onError={setError} /> : null}
      {step === 'uploading' ? <div className="activation-loader"><p>Generating license…</p></div> : null}
      {step === 'done' && result ? (
        <div className="manual-activation-result">
          <h3>Success</h3>
          <p>Your license is ready to download.</p>
          {result.license.product ? (
            <ActivationProductCard
              product={result.license.product}
              description={
                <p className="hint">
                  {result.license.activeNumberOfActivations} of {result.license.maxNumberOfActivations} devices activated
                </p>
              }
            >
              <a
                className="submit"
                href={result.url}
                target="_blank"
                rel="noopener"
                download="license-file.mb"
              >
                Download license file
              </a>
            </ActivationProductCard>
          ) : null}
          <button type="button" className="logout" onClick={reset}>
            Activate another device
          </button>
        </div>
      ) : null}
    </div>
  )
}
